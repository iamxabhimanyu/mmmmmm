export function getTranslation(key: string, lang: string = 'en'): string {
  const safeLang = (lang in TRANSLATIONS ? lang : 'en') as SupportedLanguage;
  if (TRANSLATIONS[safeLang] && TRANSLATIONS[safeLang][key]) {
    return TRANSLATIONS[safeLang][key];
  }
  return TRANSLATIONS.en[key] || key;
}

export function getOnboardingText(lang: string = 'en') {
  const safeLang = (lang in ONBOARDING_TRANSLATIONS ? lang : 'en') as SupportedLanguage;
  return ONBOARDING_TRANSLATIONS[safeLang] || ONBOARDING_TRANSLATIONS.en;
}
